pub fn get(id: &str) -> Option<&'static MarkDef> {
    MARKS.iter().find(|m| m.id == id)
}

pub fn check_integrity() {
    for mk in MARKS {
        assert!((1..=3).contains(&mk.tier), "{}", mk.id);
        assert!(!mk.text.contains('!'));
    }
    for b in super::backgrounds::BACKGROUNDS {
        if let Some(mid) = b.unlock_mark {
            assert!(get(mid).is_some(), "background {} needs unknown mark {mid}", b.id);
        }
    }
}

//! Marks: the game's achievements. Earned in a run (from state and the event
//! stream) or across runs (from the profile). Evaluation is in `meta.rs`.

use super::Difficulty;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Earn {
    /// Survive this many nights in one run.
    Nights(u32),
    /// Leave on the ferry.
    Win,
    WinOn(Difficulty),
    WinNoShot,
    WinWithDog,
    WinNoKill,
    WinBefore(u32),
    /// Be alive at dawn on the day the river freezes.
    Freeze,
    /// A full day under this much noise.
    QuietDay(u32),
    /// This many full days in a row under 20 noise.
    QuietStreak(u32),
    FieldGuideFull,
    NotesFull,
    PhotosFull,
    RadioFull,
    DieOnDay(u32),
    Kills(u32),
    LifetimeKills(u32),
    AllPlaces,
    AllStations(u8),
    AnyStation(u8),
    DogJoined,
    DogLost,
    AnySkill(u8),
    AllSkills(u8),
    Trades(u32),
    Fish(u32),
    Snared(u32),
    Harvests(u32),
    Treated(u32),
    WalkIce,
    NightReturn,
    BreachSurvived,
    /// A flag set by an event.
    Flag(&'static str),
    DailyDone,
    DailyStreak(u32),
    LifetimeRuns(u32),
    /// Percent of the codex ever found, across all runs.
    LifetimeCodex(u32),
}

impl Earn {
    /// Marks that can only be judged with the profile (across runs).
    pub fn is_lifetime(self) -> bool {
        matches!(
            self,
            Earn::LifetimeKills(_) | Earn::DailyStreak(_) | Earn::LifetimeRuns(_) | Earn::LifetimeCodex(_)
        )
    }
}

#[derive(Clone, Copy, Debug)]
pub struct MarkDef {
    pub id: &'static str,
    pub name: &'static str,
    pub text: &'static str,
    /// 1 (faint) to 3 (deep).
    pub tier: u8,
    pub hidden: bool,
    pub icon: &'static str,
    pub earn: Earn,
}

const fn m(
    id: &'static str,
    name: &'static str,
    text: &'static str,
    tier: u8,
    hidden: bool,
    icon: &'static str,
    earn: Earn,
) -> MarkDef {
    MarkDef {
        id,
        name,
        text,
        tier,
        hidden,
        icon,
        earn,
    }
}

